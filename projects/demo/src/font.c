#define NUM_GLYPHS (sizeof(GLYPHS) / sizeof(GLYPHS[0]))

/* One 8x8 16bpp glyph is 128 bytes. Index 0 is reserved for space. */
static u16 *s_glyph_data[2][NUM_GLYPHS + 1];

static
u16
lerp_rgb15(u16 a_, u16 b_, s32 t_, s32 n_)
{
  s32 r = ((a_ >> 10) & 31) + (((((b_ >> 10) & 31) - ((a_ >> 10) & 31)) * t_) / n_);
  s32 g = ((a_ >>  5) & 31) + (((((b_ >>  5) & 31) - ((a_ >>  5) & 31)) * t_) / n_);
  s32 b = ((a_      ) & 31) + (((((b_      ) & 31) - ((a_      ) & 31)) * t_) / n_);
  return (u16)MakeRGB15(r,g,b);
}

static
void
render_glyph(u16 *dst_, const GlyphDef *g_, u16 top_, u16 bottom_)
{
  s32 x, y;
  const u16 shadow = (u16)MakeRGB15(3,2,5);

  for(y = 0; y < 8 * 8; y++)
    dst_[y] = 0; /* 0 = transparent */

  /* drop shadow first, then the face on top */
  for(y = 0; y < 7; y++)
    for(x = 0; x < 5; x++)
      if(g_->rows[y][x] == '1')
        dst_[((y + 1) * 8) + (x + 1)] = shadow;

  for(y = 0; y < 7; y++)
    for(x = 0; x < 5; x++)
      if(g_->rows[y][x] == '1')
        dst_[(y * 8) + x] = lerp_rgb15(top_,bottom_,y,6);
}

Err
font_init(void)
{
  u32 i;
  s32 style;
  /* style 0: Claude coral -> warm gold. style 1: ice -> violet */
  const u16 tops[2]    = { MakeRGB15(31,26,12), MakeRGB15(20,31,31) };
  const u16 bottoms[2] = { MakeRGB15(27,12, 8), MakeRGB15(18,10,31) };

  for(style = 0; style < 2; style++)
    {
      for(i = 0; i <= NUM_GLYPHS; i++)
        {
          s_glyph_data[style][i] = (u16*)AllocMem(8 * 8 * 2, MEMTYPE_CEL);
          if(s_glyph_data[style][i] == NULL)
            return -1;
          if(i == 0)
            memset(s_glyph_data[style][i], 0, 8 * 8 * 2);
          else
            render_glyph(s_glyph_data[style][i], &GLYPHS[i - 1], tops[style], bottoms[style]);
        }
    }

  return 0;
}

void *
font_glyph(char c_, s32 style_)
{
  u32 i;

  if(c_ >= 'a' && c_ <= 'z')
    c_ = (char)(c_ - 'a' + 'A');
  for(i = 0; i < NUM_GLYPHS; i++)
    if(GLYPHS[i].ch == c_)
      return s_glyph_data[style_ & 1][i + 1];

  return s_glyph_data[style_ & 1][0];
}
